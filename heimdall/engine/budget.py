"""Бюджет памяти запроса: отказ до аллокации, а не OOM после неё.

Что здесь происходит
--------------------
Колоночное чтение поднимает колонку **целиком**: и с диска, и из процедурного
генератора. Поэтому стоимость запроса определяется числом упомянутых колонок и
числом строк витрины — но не ``limit``. Запрос со ``limit: 1`` по всем 642
колонкам ``dm_core.employee_actual`` стоит ровно столько же, сколько со
``limit: 1000``, и на корпусе в 294 000 человек это около 16,7 ГБ.

Почему отказ, а не аккуратная аллокация
---------------------------------------
Внутри одного запроса колонки нужны одновременно: ``_rows`` собирает строку
поперёк колонок, фильтрам и сортировке тоже нужен произвольный доступ. Вытеснять
колонку посреди проекции бессмысленно — её тут же придётся сгенерировать заново.
Настоящее решение — другая модель исполнения (предикаты поколоночно, сборка строк
вторым проходом по выжившим), и это переписывание ``execute.py``. Гейт же не
аллоцирует ничего, чтобы принять решение.

Почему оценка, а не замер
-------------------------
Вердикт обязан быть детерминированным: одно и то же тело запроса должно получать
один и тот же ответ независимо от данных, порядка обращений и загрузки машины.
Иначе разваливаются replay-фикстуры и кэш прогонов — то, на чём держится
воспроизводимость всего оффлайн-контура. Замер по факту аллокации был бы точнее,
но давал бы плавающий вердикт.

Почему это не каверза
---------------------
Каверза — место, где сервис отвечает 200 OK и неверно. Здесь честная ошибка с
кодом и подсказкой, и выключаться вместе с ``traps_enabled`` она не должна:
боевой сервис поверх ClickHouse на абсурдно широком запросе тоже откажет.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from ..catalog.model import Model
from .errors import fail

#: Байт на строку на колонку. Замерено на корпусе `data` (294 000 человек)
#: как прирост RSS процесса при материализации колонки целиком:
#: скаляр 17,5 МБ / 294 000, массив 31,7 МБ / 294 000,
#: эмбеддинг 483 МБ / 32 522 (384 измерения).
#: Это оценки для конкретного корпуса, а не универсальные константы; при смене
#: формы данных их нужно перезамерить — см. docs/query-budget.md.
SCALAR_BYTES_PER_ROW = 60
ARRAY_BYTES_PER_ROW = 108
EMBEDDING_BYTES_PER_ROW = 15_000

#: 4 ГиБ — около 155 колонок на витрине в 294 000 строк. Потолок выбран так,
#: чтобы разведочный запрос проходил, а чтение всего каталога — нет.
DEFAULT_MAX_BYTES = 4 * 1024 ** 3

#: Опознание эмбеддингов по имени. Дубликат правила из
#: ``b2e.gen.fillers.is_embedding``: по типу их не отличить — и вектор на 384
#: измерения, и массив из пяти элементов это ``Array(...)``. Совпадение двух
#: правил на всех именах каталога стережёт тест, а не соглашение.
_EMBEDDING = re.compile(r"emb$|embs$|embedding|_emb_|vector$")


def is_embedding(name: str) -> bool:
    return bool(_EMBEDDING.search(name))


@dataclass(frozen=True)
class Budget:
    """Потолок памяти на один запрос. ``max_bytes <= 0`` выключает гейт."""

    max_bytes: int = DEFAULT_MAX_BYTES

    @property
    def enabled(self) -> bool:
        return self.max_bytes > 0

    @classmethod
    def off(cls) -> "Budget":
        return cls(max_bytes=0)


def column_bytes(name: str, member, rows: int) -> int:
    """Оценка памяти одной материализованной колонки."""
    if rows <= 0:
        return 0
    if is_embedding(name):
        return rows * EMBEDDING_BYTES_PER_ROW
    if member is not None and member.ch.is_array:
        return rows * ARRAY_BYTES_PER_ROW
    return rows * SCALAR_BYTES_PER_ROW


def estimate_bytes(model: Model, names, rows: int) -> int:
    """Оценка памяти запроса: сумма по всем колонкам, которые он поднимет.

    Имена, которых нет в модели, пропускаются: их отвергает ``unknown-column``
    на разборе тела, и подменять чужую ошибку своей гейт не должен.
    """
    total = 0
    for name in names:
        member = model.member(name)
        if member is None:
            continue
        total += column_bytes(name, member, rows)
    return total


def enforce(model: Model, names, rows: int, budget: Budget) -> None:
    """Отказать, если запрос не помещается в бюджет."""
    if not budget.enabled:
        return
    needed = estimate_bytes(model, names, rows)
    if needed <= budget.max_bytes:
        return
    raise fail(
        "query-too-expensive",
        f"запрос читает {len(set(names))} колонок × {rows} строк витрины "
        f"{model.key} — около {needed // 1024 ** 2} МБ при бюджете "
        f"{budget.max_bytes // 1024 ** 2} МБ",
    )
